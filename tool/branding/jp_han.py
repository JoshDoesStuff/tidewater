# Writes lib/core/text/jp_han.dart: the Han characters that exist in Japanese
# encodings (JIS X 0208 plus the Windows additions). A Han character outside
# that set is practically never Japanese (it is simplified Chinese), which is
# how the app tells Chinese titles from Japanese ones when there is no kana to
# go by.
# Run: uv run python tool/branding/jp_han.py


def in_jis(c):
    try:
        chr(c).encode("cp932")
        return True
    except UnicodeEncodeError:
        return False


codes = list(range(0x3400, 0x4DC0)) + list(range(0x4E00, 0xA000)) + list(range(0xF900, 0xFB00))
text = "".join(chr(c) for c in codes if in_jis(c))

with open("lib/core/text/jp_han.dart", "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tool/branding/jp_han.py. Do not edit.\n\n")
    f.write("/// Han characters found in Japanese encodings (JIS X 0208 and the Windows additions).\n")
    f.write("const jpHan =\n")
    for i in range(0, len(text), 60):
        end = ";\n" if i + 60 >= len(text) else "\n"
        f.write("    '" + text[i : i + 60] + "'" + end)
print(len(text), "han characters")
